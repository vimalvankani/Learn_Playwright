let arr = [1,2,3,4,5]; // Length = 5
console.log(arr);

arr.push(6);    //Added 6 at the end of the array
console.log(arr);   

arr.pop();  //Added 6 and removed 6
console.log(arr);

arr.unshift(0); // Added 0 at the beginning
console.log(arr);

arr.shift(); // Remove first element
console.log(arr);